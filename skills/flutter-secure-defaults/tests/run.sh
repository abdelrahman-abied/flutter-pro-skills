#!/usr/bin/env bash
# Tests for flutter-secure-defaults/scripts/check_secure_defaults.py.
# No Flutter SDK or pub get needed: the checker is static. bash 3.2 compatible.
# Vendor-format secrets are assembled from fragments into a temp copy at run time,
# so the repository itself never contains a string that a secret scanner would block.
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILL="$(cd "$HERE/.." && pwd)"
CHECK="$SKILL/scripts/check_secure_defaults.py"
FIX="$HERE/fixtures"
TMP="$(mktemp -d "${TMPDIR:-/tmp}/seccheck.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
fail=0
export FLUTTER_SECURITY_AUDIT_DIR="$TMP/no-audit-here"

pass() { echo "PASS $1"; }
bad() { echo "FAIL $1"; fail=1; }

# assert <name> <json-file> <python-expression over d (the report) and ids (set of rule ids)>
assert() {
  local name="$1" file="$2" expr="$3"
  if python3 -I - "$file" "$expr" <<'PY'
import json, sys
d = json.load(open(sys.argv[1], encoding='utf-8'))
ids = {f['id'] for f in d['findings']}
def at(rel, line, rid=None):
    return [f for f in d['findings'] if f['file'] == rel and f['line'] == line and (rid is None or f['id'] == rid)]
def sev(rel, line, rid):
    hits = at(rel, line, rid)
    return hits[0]['severity'] if hits else None
ok = eval(sys.argv[2])
if not ok:
    sys.stderr.write('    expression was false: %s\n' % sys.argv[2])
    sys.stderr.write('    findings: %s\n' % sorted((f['id'], f['severity'], f['file'], f['line']) for f in d['findings']))
sys.exit(0 if ok else 1)
PY
  then pass "$name"; else bad "$name"; fi
}

checksum() { (cd "$1" && find . -type f | LC_ALL=C sort | while read -r f; do cksum "$f"; done); }

# --- syntax: stays Python 3.8 compatible
if python3 -I -c "import ast,sys; ast.parse(open(sys.argv[1]).read(), feature_version=(3, 8))" "$CHECK" 2>/dev/null; then
  pass "check_secure_defaults.py parses as Python 3.8"
else
  bad "check_secure_defaults.py parses as Python 3.8"
fi

# --- build the violations copy, adding vendor-format secrets from fragments
V="$TMP/violations"
cp -R "$FIX/violations" "$V"
r20="Ab3dEf6hIj9kLm2nOp5q"
STRIPE="sk_""live_${r20}Rs8t"
GITHUB="gh""p_${r20}${r20}"; GITHUB="${GITHUB:0:40}"
AWS="AK""IA${r20}"; AWS="$(printf '%s' "${AWS:0:20}" | tr 'a-z' 'A-Z')"
GKEY="AI""za${r20}${r20}"; GKEY="${GKEY:0:39}"
URLPW="Zq7${r20}"
b64() { python3 -I -c "import base64,sys; print(base64.urlsafe_b64encode(sys.argv[1].encode()).decode().rstrip('='))" "$1"; }
JWT_SVC="$(b64 '{"alg":"HS256","typ":"JWT"}').$(b64 '{"iss":"supabase","role":"service_role"}').${r20}Xy"
JWT_ANON="$(b64 '{"alg":"HS256","typ":"JWT"}').$(b64 '{"iss":"supabase","role":"anon"}').${r20}Wv"
cat > "$V/lib/core/keys.dart" <<EOF
// Generated by tests/run.sh: vendor-format test secrets (not real).
const stripeSecret = '$STRIPE';
const githubToken = '$GITHUB';
const awsKeyId = '$AWS';
const mapsKey = '$GKEY';
const serviceRoleKey = '$JWT_SVC';
const anonKey = '$JWT_ANON';
const dbUrl = 'postgres://admin:$URLPW@db.shop.dev:5432/app';
EOF
cat > "$V/lib/firebase_options.dart" <<EOF
import 'package:firebase_core/firebase_core.dart';

class DefaultFirebaseOptions {
  static const android = FirebaseOptions(apiKey: '$GKEY', appId: '1:1:android:1', messagingSenderId: '1', projectId: 'shop');
}
EOF
SECRETS="$STRIPE $GITHUB $AWS $GKEY $JWT_SVC $JWT_ANON $URLPW a8F3kQ9zLm2Xw7Pv4Tn6 zX9qL2mV7tR4wK8p"

before="$(checksum "$V")"
python3 -I "$CHECK" "$V" --json > "$TMP/v.json"; rc=$?
[ $rc = 0 ] && pass "violations: exit 0 with findings" || bad "violations: exit 0 with findings (got $rc)"
python3 -I "$CHECK" "$V" --max 50 > "$TMP/v.txt"
after="$(checksum "$V")"
[ "$before" = "$after" ] && pass "read-only: project unchanged" || bad "read-only: project unchanged"

for n in 001 002 003 004 005 006 007 008 009 010 011 012; do
  assert "violations: SEC-$n triggered" "$TMP/v.json" "'SEC-$n' in ids"
done

A=lib/features/auth
assert "SEC-001 high for SharedPreferences, Hive and a drift column" "$TMP/v.json" \
  "sev('$A/data/sources/auth_local_source.dart', 14, 'SEC-001') == 'high' and sev('$A/data/sources/auth_local_source.dart', 15, 'SEC-001') == 'high' and sev('$A/data/sources/session_db.dart', 10, 'SEC-001') == 'high'"
assert "SEC-001 ignores timestamps and settings" "$TMP/v.json" "not at('$A/data/sources/auth_local_source.dart', 17) and not at('$A/data/sources/auth_local_source.dart', 18)"
assert "SEC-002 header built in a notifier" "$TMP/v.json" "sev('$A/presentation/notifier/auth_notifier.dart', 20, 'SEC-002') == 'medium'"
assert "SEC-002 not reported in the data layer" "$TMP/v.json" "not [f for f in d['findings'] if f['id'] == 'SEC-002' and '/data/' in f['file']]"
assert "SEC-003 medium for an API base URL" "$TMP/v.json" "sev('lib/core/network/dio_client.dart', 8, 'SEC-003') == 'medium'"
assert "SEC-003 skips emulator host, namespaces, scheme checks" "$TMP/v.json" "len([f for f in d['findings'] if f['id'] == 'SEC-003']) == 1"
assert "SEC-004 graded: analytics high, print medium, kDebugMode low" "$TMP/v.json" \
  "sev('$A/presentation/notifier/auth_notifier.dart', 23, 'SEC-004') == 'high' and sev('$A/presentation/notifier/auth_notifier.dart', 22, 'SEC-004') == 'medium' and sev('$A/presentation/notifier/auth_notifier.dart', 26, 'SEC-004') == 'low'"
assert "SEC-004 skips prose, booleans and isNotEmpty" "$TMP/v.json" "not at('$A/presentation/notifier/auth_notifier.dart', 29) and not at('$A/presentation/notifier/auth_notifier.dart', 30)"
assert "SEC-004 leaves form-field values to FORM-004" "$TMP/v.json" "not [f for f in d['findings'] if f['file'].endswith('login_view.dart')]"
assert "SEC-005 LogInterceptor without kDebugMode" "$TMP/v.json" "sev('lib/core/network/dio_client.dart', 9, 'SEC-005') == 'medium'"
assert "SEC-006 block-body badCertificateCallback" "$TMP/v.json" "sev('lib/core/network/dio_client.dart', 12, 'SEC-006') == 'high'"
assert "SEC-007 WebView JS with no guard" "$TMP/v.json" "sev('lib/features/help/presentation/view/help_view.dart', 15, 'SEC-007') == 'medium'"
K=lib/core/keys.dart
assert "SEC-008 vendor keys high, Google key medium" "$TMP/v.json" \
  "sev('$K', 2, 'SEC-008') == 'high' and sev('$K', 3, 'SEC-008') == 'high' and sev('$K', 4, 'SEC-008') == 'high' and sev('$K', 5, 'SEC-008') == 'medium'"
assert "SEC-008 JWT graded by role: service_role high, anon info" "$TMP/v.json" "sev('$K', 6, 'SEC-008') == 'high' and sev('$K', 7, 'SEC-008') == 'info'"
assert "SEC-008 credentials in a URL" "$TMP/v.json" "sev('$K', 8, 'SEC-008') == 'high'"
assert "SEC-008 Firebase apiKey is info" "$TMP/v.json" "sev('lib/firebase_options.dart', 4, 'SEC-008') == 'info'"
assert "SEC-008 generic credential medium; key names and labels skipped" "$TMP/v.json" \
  "sev('lib/core/config.dart', 5, 'SEC-008') == 'medium' and not at('lib/core/config.dart', 7) and not at('lib/core/config.dart', 8)"
assert "SEC-009 graded: secret default medium, .env secret medium, API key low, bundled .env medium" "$TMP/v.json" \
  "sev('lib/core/config.dart', 12, 'SEC-009') == 'medium' and sev('lib/core/config.dart', 14, 'SEC-009') == 'medium' and sev('lib/core/config.dart', 13, 'SEC-009') == 'low' and sev('pubspec.yaml', 22, 'SEC-009') == 'medium'"
assert "SEC-010 graded: global/static medium, UI state low" "$TMP/v.json" \
  "sev('lib/core/session.dart', 2, 'SEC-010') == 'medium' and sev('$A/presentation/notifier/auth_notifier.dart', 13, 'SEC-010') == 'medium' and sev('$A/presentation/state/auth_state.dart', 13, 'SEC-010') == 'low' and not at('lib/core/session.dart', 5)"
assert "SEC-011 medium for a body logged in an auth source" "$TMP/v.json" "sev('$A/data/sources/auth_local_source.dart', 23, 'SEC-011') == 'medium'"
assert "SEC-012 only the unobfuscated release build" "$TMP/v.json" "[(f['file'], f['line']) for f in d['findings'] if f['id'] == 'SEC-012'] == [('.github/workflows/release.yml', 7)]"
assert "notes carry the profile's placement" "$TMP/v.json" "at('$A/presentation/notifier/auth_notifier.dart', 20, 'SEC-002')[0]['note'].split('. ')[-1].startswith(('Riverpod:', 'MVN:'))"

# --- secrets are never printed
leak=0
for s in $SECRETS; do
  if grep -qF -- "$s" "$TMP/v.json" "$TMP/v.txt"; then echo "    leaked: ${s:0:4}…"; leak=1; fi
done
[ $leak = 0 ] && pass "never prints a secret value (text and JSON)" || bad "never prints a secret value (text and JSON)"
grep -qF 'AIza…(39 chars)' "$TMP/v.txt" && pass "masked form shows prefix and length (AIza…(39 chars))" || bad "masked form shows prefix and length"
grep -qF 'sk_live_…(32 chars)' "$TMP/v.txt" && pass "masked vendor prefix kept (sk_live_…)" || bad "masked vendor prefix kept (sk_live_…)"

# --- JSON contract (§14)
assert "JSON: schema and top-level keys" "$TMP/v.json" "d['schema'] == 'flutter-pro-skills/flutter-secure-defaults@1' and set(d) >= {'schema','root','package','profile','stats','findings','suppressed','classification','deep_audit'}"
assert "JSON: finding keys" "$TMP/v.json" "all(set(f) == {'id','name','severity','file','line','evidence','message','note'} for f in d['findings'])"
assert "JSON: severities and IDs are known" "$TMP/v.json" "all(f['severity'] in ('high','medium','low','info') and f['id'].startswith('SEC-0') for f in d['findings'])"
assert "JSON: profile and stats" "$TMP/v.json" "set(d['profile']) >= {'presentation','source'} and set(d['stats']) >= {'files','config_files','secure_storage','http_clients'}"

# --- text output (§14)
python3 -I "$CHECK" "$V" --max 1 > "$TMP/v1.txt"
head -1 "$TMP/v1.txt" | grep -q '^== SECURITY DEFAULTS$' && pass "text: header" || bad "text: header"
grep -Eq '^  \[SEC-001\] token-in-plain-storage \(high\) x[0-9]+ — ' "$TMP/v1.txt" && pass "text: group line format" || bad "text: group line format"
grep -Eq '^      lib/[^ ]+\.dart:[0-9]+  ' "$TMP/v1.txt" && pass "text: location lines" || bad "text: location lines"
grep -Eq '^      \.\.\. [0-9]+ more$' "$TMP/v1.txt" && pass "text: --max collapses extra locations" || bad "text: --max collapses extra locations"

# --- deep audit: says whether flutter-security-audit is installed
grep -q 'deep audit: flutter-security-audit not installed .*github.com/abdelrahman-abied/flutter-security-audit' "$TMP/v.txt" \
  && pass "deep audit: not installed, says how to install" || bad "deep audit: not installed, says how to install"
mkdir -p "$TMP/audit"; printf '#!/usr/bin/env bash\n' > "$TMP/audit/scan.sh"
FLUTTER_SECURITY_AUDIT_DIR="$TMP/audit" python3 -I "$CHECK" "$FIX/clean" --json > "$TMP/da.json"
assert "deep audit: installed, gives the scan.sh command" "$TMP/da.json" "d['deep_audit']['installed'] and d['deep_audit']['command'].startswith('bash ') and 'scan.sh' in d['deep_audit']['command']"

# --- --files
python3 -I "$CHECK" "$V" --json --files "lib/core/network/dio_client.dart,pubspec.yaml" > "$TMP/f.json"
assert "--files: only listed files (comma list)" "$TMP/f.json" "d['findings'] and all(f['file'] in ('lib/core/network/dio_client.dart','pubspec.yaml') for f in d['findings'])"
echo ".github/workflows/release.yml" > "$TMP/list.txt"
python3 -I "$CHECK" "$V" --json --files "$TMP/list.txt" > "$TMP/f2.json"
assert "--files: list file, config files included" "$TMP/f2.json" "ids == {'SEC-012'}"

# --- bloc fixture: other APIs and the bloc placement
python3 -I "$CHECK" "$FIX/bloc_violations" --json > "$TMP/b.json"
BL=lib/features/account
assert "bloc: GetStorage and sqflite password column" "$TMP/b.json" "sev('$BL/data/account_store.dart', 12, 'SEC-001') == 'high' and sev('$BL/data/account_store.dart', 13, 'SEC-001') == 'high'"
assert "bloc: Crashlytics log is high" "$TMP/b.json" "sev('$BL/bloc/account_bloc.dart', 11, 'SEC-004') == 'high'"
assert "bloc: PrettyDioLogger and validateCertificate" "$TMP/b.json" "sev('lib/core/api_client.dart', 7, 'SEC-005') == 'medium' and sev('lib/core/api_client.dart', 8, 'SEC-006') == 'high'"
assert "bloc: InAppWebView guard that never fires" "$TMP/b.json" "'useShouldOverrideUrlLoading' in at('$BL/view/statement_page.dart', 10, 'SEC-007')[0]['note']"
assert "bloc: token in HydratedBloc state is medium" "$TMP/b.json" "sev('$BL/bloc/account_state.dart', 6, 'SEC-010') == 'medium'"
assert "bloc: envied secret medium, API key low, no SEC-010 double" "$TMP/b.json" "sev('lib/core/env.dart', 8, 'SEC-009') == 'medium' and sev('lib/core/env.dart', 10, 'SEC-009') == 'low' and not [f for f in d['findings'] if f['file'] == 'lib/core/env.dart' and f['id'] == 'SEC-010']"
assert "bloc: Makefile release build" "$TMP/b.json" "sev('Makefile', 2, 'SEC-012') == 'low'"
assert "bloc: placement note follows the bloc profile" "$TMP/b.json" "'Bloc:' in at('$BL/data/account_store.dart', 12, 'SEC-001')[0]['note']"

# --- clean fixture
python3 -I "$CHECK" "$FIX/clean" --json > "$TMP/c.json"
assert "clean: zero findings, nothing suppressed" "$TMP/c.json" "d['findings'] == [] and d['suppressed'] == []"
assert "clean: secure storage detected" "$TMP/c.json" "d['stats']['secure_storage'] == ['flutter_secure_storage']"
python3 -I "$CHECK" "$FIX/clean" > "$TMP/c.txt"
grep -q 'no security-default findings' "$TMP/c.txt" && pass "clean: text says no findings" || bad "clean: text says no findings"

# --- suppression
python3 -I "$CHECK" "$FIX/suppressed" --json > "$TMP/s.json"
assert "suppress: a wrong rule id does not suppress" "$TMP/s.json" "[(f['id'], f['file'], f['line']) for f in d['findings']] == [('SEC-004', 'lib/src/line_ignored.dart', 8)]"
assert "suppress: same-line, line-above, file and YAML # comments honoured" "$TMP/s.json" "sorted((s['id'], s['file'], s['line']) for s in d['suppressed']) == [('SEC-001','lib/src/line_ignored.dart',4), ('SEC-003','lib/src/line_ignored.dart',6), ('SEC-010','lib/src/file_ignored.dart',2), ('SEC-010','lib/src/file_ignored.dart',3), ('SEC-012','.github/workflows/build.yml',8)]"
assert "suppress: reasons kept" "$TMP/s.json" "all(s['reason'] and s['reason'] != '(no reason given)' for s in d['suppressed'])"
python3 -I "$CHECK" "$FIX/suppressed" | grep -q '^  suppressed: 5 (see --json)$' && pass "suppress: text summary line" || bad "suppress: text summary line"

# --- fallback without the flutter-architecture sibling
mkdir -p "$TMP/lonely/scripts"
cp "$CHECK" "$TMP/lonely/scripts/check_secure_defaults.py"
python3 -I "$TMP/lonely/scripts/check_secure_defaults.py" "$V" --json > "$TMP/fb.json"
assert "fallback: says it used path-based classification" "$TMP/fb.json" "d['classification'].startswith('path-based fallback')"
assert "fallback: every rule still fires" "$TMP/fb.json" "ids == {'SEC-%03d' % i for i in range(1, 13)}"
assert "fallback: profile from pubspec/folders" "$TMP/fb.json" "d['profile']['presentation'] == 'mvn' and d['profile']['source'].startswith('fallback')"
python3 -I "$TMP/lonely/scripts/check_secure_defaults.py" "$FIX/clean" --json > "$TMP/fbc.json"
assert "fallback: clean fixture still zero" "$TMP/fbc.json" "d['findings'] == []"
python3 -I "$TMP/lonely/scripts/check_secure_defaults.py" "$V" | grep -q '^  classification: path-based fallback' && pass "fallback: text output says so" || bad "fallback: text output says so"

# --- --profile override
python3 -I "$CHECK" "$FIX/bloc_violations" --json --profile getx > "$TMP/p.json"
assert "--profile overrides detection and the placement note" "$TMP/p.json" "d['profile']['presentation'] == 'getx' and d['profile']['source'].startswith('declared') and 'GetX:' in at('$BL/data/account_store.dart', 12, 'SEC-001')[0]['note']"

# --- usage errors and edge cases
python3 -I "$CHECK" "$TMP" >/dev/null 2>&1; rc=$?
[ $rc = 2 ] && pass "exit 2 without pubspec.yaml" || bad "exit 2 without pubspec.yaml (got $rc)"
python3 -I "$CHECK" "$FIX/clean" --bogus >/dev/null 2>&1; rc=$?
[ $rc = 2 ] && pass "exit 2 on unknown option" || bad "exit 2 on unknown option (got $rc)"
python3 -I "$CHECK" "$FIX/clean" --profile nope >/dev/null 2>&1; rc=$?
[ $rc = 2 ] && pass "exit 2 on unknown profile" || bad "exit 2 on unknown profile (got $rc)"
python3 -I "$CHECK" >/dev/null 2>&1; rc=$?
[ $rc = 2 ] && pass "exit 2 without arguments" || bad "exit 2 without arguments (got $rc)"
mkdir -p "$TMP/nolib"; printf 'name: nolib\n' > "$TMP/nolib/pubspec.yaml"
python3 -I "$CHECK" "$TMP/nolib" --json > "$TMP/n.json"; rc=$?
[ $rc = 0 ] && pass "no lib/: exit 0" || bad "no lib/: exit 0 (got $rc)"
assert "no lib/: empty report" "$TMP/n.json" "d['findings'] == [] and d['stats']['files'] == 0"

[ $fail = 0 ] && echo "ALL flutter-secure-defaults TESTS PASSED" || echo "flutter-secure-defaults: SOME TESTS FAILED"
exit $fail
